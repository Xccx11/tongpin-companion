package com.aster.companion.agent

/**
 * 出图前的**校验轮**：拿已经写好的提示词对画面草稿逐条核对，把错的改对。
 *
 * 为什么需要：9B 的 Scene 模型会**违背草稿里明写的东西**——实测把「已经全脱了」写成穿着白衬衫
 * 包臀裙、把全身的景别写成 `close-up`、把草稿里的第二个人整个弄丢。规则写得再细它也会漏，
 * 所以最后一轮专门用来纠错：只改错的地方，**不许把细节改少**。
 *
 * 外貌档案是**补全依据**，不是"该删的东西"：并不是每条出图路径都会由 [AppearanceAnchor] 把原文
 * 拼在提示词最前面（直接出图那条就故意不拼，怕中文长相和英文画面混在一起把编码搞糊），
 * 所以校验轮必须保证长相要点**完整地留在提示词里**——以前写成"发现就删掉"，结果整段眼睛、鼻子、
 * 肤色、身材在最后一轮被删光，画出来就是另一个人。
 */
object SceneVerifier {

    data class Prompt(val system: String, val user: String)

    fun prompt(
        rule: String,
        draft: String,
        appearance: String,
        candidate: String,
        format: ScenePromptFormat
    ): Prompt = Prompt(
        system = buildString {
            appendLine(rule.trim())
            if (appearance.isNotBlank()) {
                appendLine()
                appendLine("**她的长相档案（用户原文，一个字都不许改）**：")
                appendLine(appearance.trim())
            }
            appendLine(ScenePromptRefiner.formRequirement(format))
            appendLine("只输出提示词本体，不要解释、不要 markdown、不要 WHY 行。")
            appendLine("长度不超过 ${ScenePromptRefiner.MAX_CHARS} 个字符。")
        }.trim(),
        user = buildString {
            appendLine("【画面草稿 —— 需求以它为准】")
            appendLine(draft.trim())
            appendLine()
            appendLine("【已经写好的出图提示词 —— 请逐条核对并修正】")
            appendLine(candidate.trim())
        }.trim()
    )

    /** 网关上取不到 `image.sceneVerify.*` 时的兜底规则；与远程同义。 */
    fun defaultRule(format: ScenePromptFormat): String = CHINESE_RULE

    private val CHINESE_RULE = """你在做出图前的**最后一道校验**。给你的画面草稿是需求方，第二段是已经写好的提示词。

**任务：拿提示词逐条对草稿核对，把错的地方改对，然后只输出修正后的提示词全文。**

1. **人**：草稿里出现的每一个人（她 + 对方／"你"／"他"）都必须有——对方的身体在哪、他的哪个部位
   贴着她／进入她／抓住她、他在动的是什么、画面里能看到他的什么。**只剩她一个人就是错的。**
2. **穿着与暴露**：必须和草稿的穿着状态一致。草稿写"已经全脱了"就**绝不许**给写衣服。
3. **姿势**：草稿写的是哪个姿势就只能写那个姿势，不许换成别的。
4. **景别**：必须明确写了拍到哪。草稿没指定时一律算全身（从头到脚、脚不许被切）；
   写成 close-up 或半身而草稿要全身的，改回全身。
5. **长相必须完整（这条以前删错过，看仔细）**：
   提示词里**必须有**她的长相要点——脸型、眼睛的形状与颜色、头发的颜色与发型、皮肤、身材、年龄。
   被压缩成一句 "a young woman"、或者只剩一个脸型——**照上面那份长相档案原文补全，一个字都不许改**
   （外貌是用户亲手定的，改写就等于把她换成另一个人）。
   **唯一不该做的是重复**：如果提示词最前面已经原样拼着那份档案，正文里就不要再写第二遍长相。
   表情和身体动作同样不能删、少了还要补：表情（眼睛看哪、眼皮多重、嘴唇张开多少、嘴角弧度、眉头）、
   身体动作（姿势、朝向、手抓什么、腿怎么摆、身体贴着哪）。
   **判断标准：固定长相——有就留、缺就补、绝不改写；表情和动作——绝不能删。**
6. **名字**：不许出现任何名字或昵称。
7. **心情词**：草稿里标了"不要写进画面"的心情词不许当画面词出现，要落成看得见的表情。
8. **器材**：画面里不许出现手机、相机、镜头、取景框。
9. **逻辑自洽**（最容易漏的一条，认真查）：
   - **景别与细节粒度必须匹配**：写了全身（full body）就不能出现「手指陷进皮肉」「带子勒出深痕
     把肉挤得隆起」这种只有特写才看得见的微观细节；草稿说的是「对准某处、展示某处的细节」时，
     景别就该是那个部位的**特写**，而不是全身。**发现「全身 + 微观细节」就改回特写（或删掉微观细节）。**
   - **同一件东西只能在一个地方**：吊带袜的带子在大腿根部，就不许在别处写成「脚上的袜子上有吊带」；
     衣服不能既穿着又脱了；手不能同时拿两样东西。
   - **场景自洽**：写到窗户就得有窗户；写了「几乎不动」就别再写「剧烈颤抖」。

**只动错的地方**，其余一字不改；**绝对不许把细节改少**：接触点、身体状态、布料状态只能补全。
**画面里不许有光线或阴影描写**：发现 lighting/shadow/rim light/背光/明暗这类词就删掉，不要把光补回来。
输出只有修正后的提示词本体。"""
}
